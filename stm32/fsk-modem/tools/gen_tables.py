"""
Generate Core/Src/fsk_tables.c (lookup tables for the FSK modem).

    python tools/gen_tables.py

Author: Faizan Saleem Siddiqui (https://github.com/FaizanSSDQ)
"""

import math
from pathlib import Path

SINE_SIZE = 256  # modulator phase resolution (8 bits of the 32-bit phase accumulator)
SPB = 16  # samples per bit = correlator window
Q15, Q14 = 32767, 16384


def table(name: str, ctype: str, values: list[int], per_line: int = 12) -> str:
    rows = [", ".join(f"{v:6d}" for v in values[i : i + per_line])
            for i in range(0, len(values), per_line)]
    body = ",\n    ".join(rows)
    return f"const {ctype} {name}[{len(values)}] = {{\n    {body}\n}};\n"


def main() -> None:
    sine = [round(Q15 * math.sin(2 * math.pi * i / SINE_SIZE)) for i in range(SINE_SIZE)]
    # Correlator references over one bit: mark = 1 cycle per bit, space = 2 cycles per bit.
    c1 = [round(Q14 * math.cos(2 * math.pi * 1 * n / SPB)) for n in range(SPB)]
    s1 = [round(Q14 * math.sin(2 * math.pi * 1 * n / SPB)) for n in range(SPB)]
    c2 = [round(Q14 * math.cos(2 * math.pi * 2 * n / SPB)) for n in range(SPB)]
    s2 = [round(Q14 * math.sin(2 * math.pi * 2 * n / SPB)) for n in range(SPB)]

    out = [
        "/**",
        " * @file    fsk_tables.c",
        " * @brief   Lookup tables for the FSK modem. GENERATED by tools/gen_tables.py: do not edit.",
        " */",
        '#include "fsk_tables.h"',
        "",
        "/* sin(2*pi*i/256) in Q15 */",
        table("fsk_sine_q15", "int16_t", sine),
        "/* Correlator references in Q14 over one bit (16 samples) */",
        table("fsk_ref_mark_cos", "int16_t", c1, 8),
        table("fsk_ref_mark_sin", "int16_t", s1, 8),
        table("fsk_ref_space_cos", "int16_t", c2, 8),
        table("fsk_ref_space_sin", "int16_t", s2, 8),
    ]
    path = Path(__file__).resolve().parents[1] / "Core" / "Src" / "fsk_tables.c"
    path.write_bytes(("\n".join(out)).encode())  # LF line endings on every OS
    print("wrote", path)


if __name__ == "__main__":
    main()
