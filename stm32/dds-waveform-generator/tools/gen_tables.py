"""Generate Core/Src/dds_tables.c: a 256-point Q15 sine table plus a wrap entry,
so the interpolating lookup in dds.c never needs a modulo.

Run:  python tools/gen_tables.py

Author: Faizan Saleem Siddiqui (https://github.com/FaizanSSDQ)
"""

import math
from pathlib import Path

N = 256
ROOT = Path(__file__).resolve().parent.parent


def sine_table() -> list[int]:
    return [round(32767 * math.sin(2 * math.pi * k / N)) for k in range(N + 1)]


def main() -> None:
    values = sine_table()
    rows = [", ".join(f"{v:6d}" for v in values[i:i + 8]) for i in range(0, len(values), 8)]
    body = ",\n    ".join(rows)
    text = f"""/**
 * @file    dds_tables.c
 * @brief   Q15 sine table, {N} points per cycle plus one wrap entry.
 *          Generated by tools/gen_tables.py - do not edit by hand.
 * @author  Faizan Saleem Siddiqui (https://github.com/FaizanSSDQ)
 */
#include "dds_tables.h"

const int16_t dds_sine_table[DDS_SINE_POINTS + 1] = {{
    {body}
}};
"""
    (ROOT / "Core" / "Src" / "dds_tables.c").write_bytes(text.encode())
    print(f"wrote dds_tables.c ({N + 1} entries)")


if __name__ == "__main__":
    main()
