function text = export_c_header(sos, name, fs, path)
%EXPORT_C_HEADER  Write biquad coefficients as a C header for firmware.
%   text = export_c_header(sos, name, fs)          returns the header text
%   text = export_c_header(sos, name, fs, path)    and writes it to path
%
%   Two arrays are emitted:
%     <name>_f32  for CMSIS-DSP arm_biquad_cascade_df2T_f32: per section
%                 {b0, b1, b2, -a1, -a2}  (CMSIS adds the feedback terms,
%                 so the a coefficients are negated)
%     <name>_q15  for arm_biquad_cascade_df1_q15 with postShift = 1: per
%                 section {b0, 0, b1, b2, -a1, -a2} in Q14
%
%   Author: Faizan Saleem Siddiqui (https://github.com/FaizanSSDQ)

    L = size(sos, 1);
    up = upper(name);
    q = quantize_q14(sos);
    lines = {
        '/* Generated by export_c_header.m (digital-filter-designer). Do not edit. */'
        sprintf('#ifndef %s_H', up)
        sprintf('#define %s_H', up)
        ''
        '#include <stdint.h>'
        ''
        sprintf('#define %s_SECTIONS   %d', up, L)
        sprintf('#define %s_FS_HZ      %gf', up, fs)
        sprintf('#define %s_POST_SHIFT 1   /* q15: coefficients are Q14 */', up)
        ''
        '/* CMSIS-DSP arm_biquad_cascade_df2T_f32: {b0, b1, b2, -a1, -a2} per section */'
        sprintf('static const float %s_f32[%d] = {', name, 5 * L)
    };
    for k = 1:L
        s = sos(k, :);
        lines{end + 1, 1} = sprintf('    %.9ef, %.9ef, %.9ef, %.9ef, %.9ef,', s(1), s(2), s(3), -s(5), -s(6)); %#ok<AGROW>
    end
    lines = [lines; {
        '};'
        ''
        '/* CMSIS-DSP arm_biquad_cascade_df1_q15 (postShift 1): {b0, 0, b1, b2, -a1, -a2} per section */'
        sprintf('static const int16_t %s_q15[%d] = {', name, 6 * L)
    }];
    for k = 1:L
        s = q(k, :);
        lines{end + 1, 1} = sprintf('    %6d, 0, %6d, %6d, %6d, %6d,', s(1), s(2), s(3), -s(5), -s(6)); %#ok<AGROW>
    end
    lines = [lines; {'};'; ''; sprintf('#endif /* %s_H */', up)}];
    text = sprintf('%s\n', lines{:});
    if nargin >= 4
        fid = fopen(path, 'w');
        fwrite(fid, text);
        fclose(fid);
    end
end
